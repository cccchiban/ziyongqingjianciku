def pinyin_of(word):
    if word in OVERRIDES:
        return OVERRIDES[word]
    if HAN.match(word):
        syls = lazy_pinyin(word, style=Style.TONE3, neutral_tone_with_five=True,
                           v_to_u=False, errors=lambda x: list(x))
        if len(syls) != len(word):
            return None
        for s in syls:
            if not re.fullmatch(r"[a-z]+[1-5]", s):
                return None
        return " ".join(syls)
    out, run = [], ""
    for ch in word:
        if ASCII.match(ch):
            if run:
                sub = lazy_pinyin(run, style=Style.TONE3,
                                  neutral_tone_with_five=True,
                                  v_to_u=False, errors=lambda x: list(x))
                if len(sub) != len(run) or any(
                        not re.fullmatch(r"[a-z]+[1-5]", s) for s in sub):
                    return None
                out.extend(sub)
                run = ""
            out.append(ch)
        else:
            run += ch
    if run:
        sub = lazy_pinyin(run, style=Style.TONE3, neutral_tone_with_five=True,
                          v_to_u=False, errors=lambda x: list(x))
        if len(sub) != len(run) or any(
                not re.fullmatch(r"[a-z]+[1-5]", s) for s in sub):
            return None
        out.extend(sub)
    return " ".join(out)


def main():
    rows, problems, unchecked, excluded = [], [], [], []
    owner = {}
    for group, base, blob in GROUPS:
        for i, w in enumerate(blob.split()):
            if w in EXCLUDE:
                excluded.append(w); continue
            if " " in w or "\t" in w:
                problems.append(("词面含空白", w)); continue
            if len(w) < 2:
                problems.append(("单字词", w)); continue
            if w.lower() in owner:
                problems.append(("库内重复", "%s 已在 %s" % (w, owner[w.lower()])))
                continue
            py = pinyin_of(w)
            if not py:
                problems.append(("拼音不可用", w)); continue
            if len(py.split(" ")) != len(w):
                problems.append(("音节点数不符", "%s %s" % (w, py))); continue
            if w not in OVERRIDES and HAN.match(w):
                unchecked.append(w)
            owner[w.lower()] = group
            freq = max(base - min(i // 6, 6) * 10, base - 60)
            rows.append((w, py, freq))

    if problems:
        print("异常 %d 条：" % len(problems))
        for p in problems:
            print("  %s: %s" % p)
        return 1
    if not rows:
        print("词条为 0，拒绝写出", file=sys.stderr)
        return 1

    rows.sort(key=lambda r: (-r[2], r[1], r[0]))
    os.makedirs(OUT, exist_ok=True)
    with io.open(TARGET, "w", encoding="utf-8", newline="\n") as fh:
        for w, py, fr in rows:
            fh.write("%s\t%s\t%d\n" % (w, py, fr))
    ov = sum(1 for r in rows if r[0] in OVERRIDES)
    print("写出 %s：%d 条，词频 %d—%d，人工核定 %d 条，工具生成 %d 条"
          % (os.path.basename(TARGET), len(rows),
             min(r[2] for r in rows), max(r[2] for r in rows), ov, len(rows) - ov))
    if excluded:
        print("按 EXCLUDE 剔除 %d 条泛词" % len(excluded))
    return 0


